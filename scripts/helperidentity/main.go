// Command helperidentity freezes the signed helper identity for app builds.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"

	"github.com/Kel077/pith/internal/helper"
	"github.com/Kel077/pith/internal/helper/identity"
)

func generatedSource(id identity.Identity) ([]byte, error) {
	if err := id.Validate(); err != nil {
		return nil, err
	}
	data, err := json.Marshal(id)
	if err != nil {
		return nil, err
	}
	return format.Source([]byte("// Code generated by make helper; DO NOT EDIT.\n\npackage client\n\nfunc init() { bundledHelperIdentity = " + strconv.Quote(string(data)) + " }\n"))
}

func writeFile(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".identity-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	_, writeErr := f.Write(data)
	if err := errors.Join(writeErr, f.Chmod(0644), f.Close()); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func run(args []string) error {
	flags := flag.NewFlagSet("helperidentity", flag.ContinueOnError)
	source := flags.String("helper", "", "signed ARM64 helper path")
	manifest := flags.String("manifest", "", "build-only identity manifest")
	generated := flags.String("generate", "", "client Go file to generate")
	verify := flags.Bool("verify", false, "compare packaged bytes with the build identity")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 || *source == "" || *manifest == "" || (*verify && *generated != "") || (!*verify && *generated == "") {
		return errors.New("specify helper, manifest and either generate or verify")
	}
	actual, err := identity.Inspect(*source, helper.Version, helper.ProtocolVersion)
	if err != nil {
		return err
	}
	if *verify {
		data, err := os.ReadFile(*manifest)
		if err != nil {
			return err
		}
		expected, err := identity.Parse(data)
		if err != nil {
			return err
		}
		if actual != expected {
			return errors.New("packaging changed the frozen helper identity")
		}
		return nil
	}
	goSource, err := generatedSource(actual)
	if err != nil {
		return err
	}
	data, err := json.MarshalIndent(actual, "", "  ")
	if err != nil {
		return err
	}
	if err := writeFile(*manifest, append(data, '\n')); err != nil {
		return err
	}
	return writeFile(*generated, goSource)
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "pith helper identity:", err)
		os.Exit(1)
	}
}
